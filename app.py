def generate_caption_greedy(image, encoder, decoder, max_len=20):
    encoder.eval()
    decoder.eval()
    with torch.no_grad():
        feature = encoder(image.unsqueeze(0).to(device))
        word = torch.tensor([[vocab["<START>"]]]).to(device)
        caption = []
        for _ in range(max_len):
            output = decoder(feature, word)
            pred = output.argmax(2)[:, -1].item()
            if pred == vocab["<END>"]:
                break
            caption.append(inv_vocab.get(pred, "<UNK>"))
            word = torch.cat([word, torch.tensor([[pred]]).to(device)], 1)
    return " ".join(caption)

def generate_caption_beam_search(image, encoder, decoder, beam_width=5, max_len=20):
    encoder.eval()
    decoder.eval()
    with torch.no_grad():
        feature = encoder(image.unsqueeze(0).to(device))
        beams = [([vocab["<START>"]], 0.0)]
        for _ in range(max_len):
            new_beams = []
            for seq, score in beams:
                if seq[-1] == vocab["<END>"]:
                    new_beams.append((seq, score))
                    continue
                word = torch.tensor([seq]).to(device)
                output = decoder(feature, word)
                log_probs = torch.log_softmax(output[0, -1], dim=0)
                top_k_probs, top_k_indices = torch.topk(log_probs, beam_width)
                for prob, idx in zip(top_k_probs, top_k_indices):
                    new_seq = seq + [idx.item()]
                    new_score = score + prob.item()
                    new_beams.append((new_seq, new_score))
            beams = sorted(new_beams, key=lambda x: x[1], reverse=True)[:beam_width]
            if all(seq[-1] == vocab["<END>"] for seq, _ in beams):
                break
        best_seq = beams[0][0]
        caption = [inv_vocab.get(idx, "<UNK>") for idx in best_seq
                   if idx not in [vocab["<START>"], vocab["<END>"]]]
    return " ".join(caption)

