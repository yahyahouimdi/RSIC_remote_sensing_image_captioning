def build_vocab(df_list, min_freq=3):
    """Build vocabulary from dataframes"""
    counter = Counter()
    total_captions = 0

    for df in df_list:
        for idx, row in df.iterrows():
            captions = parse_captions(row['captions'])
            for caption in captions:
                tokens = word_tokenize(caption.lower())
                counter.update(tokens)
                total_captions += 1

    print(f"✓ Processed {total_captions} captions")
    print(f"✓ Found {len(counter)} unique tokens")

    vocab = {"<PAD>": 0, "<START>": 1, "<END>": 2, "<UNK>": 3}
    idx = 4
    for word, freq in counter.items():
        if freq >= min_freq:
            vocab[word] = idx
            idx += 1

    return vocab, counter

